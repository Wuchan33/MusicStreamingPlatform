        REFERENCES podcast_episodes (episode_id)
        ON DELETE CASCADE
);

CREATE INDEX idx_episode_playback_details_episode_id ON episode_playback_details (episode_id);

CREATE TABLE ad_playback_details (
    playback_id INT PRIMARY KEY,
    ad_id INT NOT NULL,

    CONSTRAINT fk_ad_playback_details_playback_history
        FOREIGN KEY (playback_id)
        REFERENCES playback_history (playback_id)
        ON DELETE CASCADE,

    CONSTRAINT fk_ad_playback_details_ads
        FOREIGN KEY (ad_id)
