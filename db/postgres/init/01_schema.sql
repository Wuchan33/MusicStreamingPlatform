--  PLAYBACK HISTORY

CREATE TABLE playback_history (
    playback_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    playback_date TIMESTAMPTZ NOT NULL DEFAULT now(),
    duration_played_seconds INT NOT NULL,
    media_type media_type NOT NULL,
    media_id INT NOT NULL,
    user_id INT NOT NULL,
    device_type_id INT NOT NULL,

    CONSTRAINT chk_playback_history_duration_played_seconds
        CHECK (duration_played_seconds >= 0),

    CONSTRAINT fk_playback_history_users
        FOREIGN KEY (user_id)
        REFERENCES users (user_id)
        ON DELETE CASCADE,

    CONSTRAINT fk_playback_history_device_types
        FOREIGN KEY (device_type_id)
        REFERENCES device_types (device_type_id)
);

CREATE INDEX idx_playback_history_user_id ON playback_history (user_id);
CREATE INDEX idx_playback_history_playback_date ON playback_history (playback_date);
CREATE INDEX idx_playback_history_device_type_id ON playback_history (device_type_id);

CREATE TABLE song_playback_details (
    playback_id INT PRIMARY KEY,
    song_id INT NOT NULL,

    CONSTRAINT fk_song_playback_details_playback_history
        FOREIGN KEY (playback_id)
        REFERENCES playback_history (playback_id)
        ON DELETE CASCADE,

    CONSTRAINT fk_song_playback_details_songs
        FOREIGN KEY (song_id)
        REFERENCES songs (song_id)
        ON DELETE CASCADE
);

CREATE INDEX idx_song_playback_details_song_id ON song_playback_details (song_id);

CREATE TABLE episode_playback_details (
    playback_id INT PRIMARY KEY,
    episode_id INT NOT NULL,

    CONSTRAINT fk_episode_playback_details_playback_history
        FOREIGN KEY (playback_id)
